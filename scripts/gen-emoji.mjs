/** emoji → twemoji 文件名（去掉变体选择符 FE0F，codepoint 小写连字符拼接） */
function toId(emoji) {
  return Array.from(emoji)
    .filter((ch) => ch.codePointAt(0) !== 0xfe0f)
    .map((ch) => ch.codePointAt(0).toString(16))
    .join('-')
}

/** 提取 <svg> 内部内容，并做轻量压缩；遇到 fabric 难以正确渲染的特性则跳过 */
function extractInner(svg) {
  if (/<filter|<mask|<pattern|<clipPath|url\(/.test(svg)) return null
  const open = svg.match(/<svg[^>]*>/)
  if (!open) return null
  const inner = svg.slice(open.index + open[0].length).replace(/<\/svg>\s*$/, '')
  // 压缩：去换行与标签间多余空白
  return inner.replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ').trim()
}

function main() {
  if (!fs.existsSync(path.join(SVG_DIR, '1f600.svg'))) {
    console.error('[gen-emoji] 未找到 @twemoji/svg，请先执行： npm i --no-save @twemoji/svg')
    process.exit(1)
  }

  const out = []
  const missing = []
  const skipped = []
  const seen = new Set()

  for (const [category, emoji, name] of CURATED) {
    const id = toId(emoji)
    if (seen.has(id)) continue
    seen.add(id)
    const file = path.join(SVG_DIR, `${id}.svg`)
    if (!fs.existsSync(file)) {
      missing.push(`${emoji} (${id}) ${name}`)
      continue
    }
    const inner = extractInner(fs.readFileSync(file, 'utf8'))
    if (!inner) {
      skipped.push(`${emoji} ${name}`)
      continue
    }
    out.push([id, name, category, emoji, inner])
  }

  const payload = {
    meta: {
      source: 'Twemoji',
      homepage: 'https://github.com/twitter/twemoji',
      license: 'CC-BY 4.0',
      licenseUrl: 'https://creativecommons.org/licenses/by/4.0/',
      viewBox: VIEWBOX,
      count: out.length,
      generatedAt: new Date().toISOString().slice(0, 10),
    },
    // [id, 中文名, 分类, emoji字符, SVG内部片段]
    emoji: out,
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
  fs.writeFileSync(OUT_FILE, JSON.stringify(payload), 'utf8')

  const kb = (fs.statSync(OUT_FILE).size / 1024).toFixed(1)
  console.log(`[gen-emoji] 已生成 ${out.length} 个表情 → src/assets/emoji-twemoji.json (${kb} KB)`)
  if (missing.length) console.log(`[gen-emoji] 未找到文件 ${missing.length} 个：${missing.join(', ')}`)
  if (skipped.length) console.log(`[gen-emoji] 特性不支持跳过 ${skipped.length} 个：${skipped.join(', ')}`)
}

main()
